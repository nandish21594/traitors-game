test('portable backup restores identities, scores, media and full audit into a fresh database, paused and with sessions revoked', () => {
  const first = tempStore(), second = tempStore();
  first.command({ type: 'demo' }, 'host');
  let s = first.command({ type: 'start' }, 'host');
  const id = s.players[3].id;
  const assetId = randomUUID(); const portrait = fixturePng();
  first.db.prepare('INSERT INTO media VALUES(?,?,?,?)').run(assetId, 'image/png', 'portrait.png', portrait);
  first.command({ type: 'photo', playerId: id, assetId }, 'host');
  first.command({ type: 'score', round: 1, playerIds: [id], mode: 'set', points: 37, reason: 'Final tally' }, 'host');
  first.command({ type: 'timer', seconds: 300 }, 'host');
  const backup = exportBackup(first); const original = structuredClone(backup.payload.state);
  assert.equal(backup.format, 'traitors-game');
  second.command({ type: 'add_player', name: 'Old game' }, 'host');
  const token = second.session('player', second.get().players[0].id);
  const restored = importBackup(second, { ...backup, format: 'diwali-traitors' }, 'Restore original version-1 snapshot');
  assert.equal(restored.id, original.id); assert.equal(restored.players[3].id, id);
  assert.equal(restored.rounds[0].scores[id], 37); assert.equal(restored.paused, true);
  assert.equal(restored.players[3].photo, assetId);
  assert(Buffer.from(second.db.prepare('SELECT data FROM media WHERE id=?').get(assetId).data).equals(portrait));
  assert.equal(restored.timer.deadline, null); assert(restored.timer.remaining >= 299);
  assert.throws(() => second.authenticate(token, 'player'), /sign in/);
  assert(second.audit().some(e => e.type === 'restore' && e.detail.sourceAudit.length >= 4));
  assert(second.audit().some(e => e.type === 'add_player'), 'Destination audit must be preserved');
  first.close(); second.close();
});
test('checksum failures and malformed backups leave the existing database untouched', () => {
  const db = tempStore(); db.command({ type: 'demo' }, 'host');
  const before = db.get(); const backup = exportBackup(db); backup.payload.state.players[0].role = 'invalid';
  assert.throws(() => importBackup(db, backup, 'Tamper test'), /checksum/);
  backup.checksum = digest(JSON.stringify(backup.payload));
  assert.throws(() => importBackup(db, backup, 'Structural test'), /invalid game/);
  assert.deepEqual(db.get(), before); assert.equal(db.audit().length, 1); db.close();
});
test('undo appends a correction, preserves events, and cannot cross a public vote or role reveal', () => {
  const db = tempStore(); db.command({ type: 'demo' }, 'host'); db.command({ type: 'start' }, 'host');
  const id = db.get().players[0].id;
  db.command({ type: 'score', round: 1, playerIds: [id], points: 10, mode: 'add', reason: 'Award' }, 'host');
  db.undo('Correct mistaken award'); assert.equal(db.get().rounds[0].scores[id] || 0, 0); assert.equal(db.audit()[0].type, 'undo');
  assert.equal(db.audit().filter(e => e.type === 'score').length, 1);
  db.command({ type: 'next' }, 'host'); db.command({ type: 'next', reason: 'No Shields this test' }, 'host');
  db.command({ type: 'close_ballot', force: true, reason: 'All abstain in rehearsal' }, 'host'); db.command({ type: 'next' }, 'host');
  db.command({ type: 'close_ballot', force: true, reason: 'All abstain in rehearsal' }, 'host');
  db.command({ type: 'reveal_next' }, 'host');
  assert.throws(() => db.undo('Cannot remove a vote from the room'), /Public votes/);
  assert.equal(currentBallot(db.get()).revealed, 1); db.close();
});
